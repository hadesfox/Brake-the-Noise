-- 第二幕 → 清算/传播：post 原文副本、方向、势能和 causalChain。
-- 完成局 → 档案：整个 session；测试索引和车辆索引分别保存。
-- 原文与历史记录一经提交不由演出层覆写；档案只接收 completed 的正式局。
